// Lists the question pictures in public/worksheet-figures so the worksheet
// pages can show them without any code changes.
//
// A picture saved as public/worksheet-figures/<worksheet id>/<question number>.png
// (or .jpg, .jpeg, .webp, .svg) belongs to that question, for example
// public/worksheet-figures/lesson-19/4.8.png. This script writes
// public/worksheet-figures/manifest.js, which worksheet.html and grade.html load.
//
// It runs automatically before `npm run dev` and `npm run build`; run
// `npm run figures` after adding pictures while the dev server is running.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "public", "worksheet-figures");
const output = path.join(root, "manifest.js");
const EXTENSIONS = [".png", ".jpg", ".jpeg", ".webp", ".svg"]; // preferred first
const SAFE_NAME = /^[A-Za-z0-9._-]+$/;

const figures = {};
const warnings = [];

if (fs.existsSync(root)) {
  for (const folder of fs.readdirSync(root, { withFileTypes: true })) {
    if (!folder.isDirectory()) continue;
    if (!SAFE_NAME.test(folder.name)) {
      warnings.push(`skipped folder "${folder.name}": use only letters, numbers, ".", "-" and "_"`);
      continue;
    }
    const found = {};
    for (const file of fs.readdirSync(path.join(root, folder.name)).sort()) {
      const extension = path.extname(file).toLowerCase();
      const number = path.basename(file, path.extname(file));
      if (!EXTENSIONS.includes(extension)) {
        warnings.push(`skipped ${folder.name}/${file}: not a .png, .jpg, .jpeg, .webp or .svg picture`);
        continue;
      }
      if (!SAFE_NAME.test(number)) {
        warnings.push(`skipped ${folder.name}/${file}: name it after the question number, e.g. 4.8${extension}`);
        continue;
      }
      if (found[number]) {
        const keep = EXTENSIONS.indexOf(path.extname(found[number])) <= EXTENSIONS.indexOf(extension) ? found[number] : file;
        warnings.push(`${folder.name}: two pictures for question ${number}; using ${keep}`);
        found[number] = keep;
      } else {
        found[number] = file;
      }
    }
    if (Object.keys(found).length) {
      figures[folder.name] = Object.fromEntries(
        Object.entries(found).map(([number, file]) => [number, `/worksheet-figures/${folder.name}/${file}`]),
      );
    }
  }
}

const content = `// Generated by scripts/build-figure-manifest.mjs. Do not edit: add or remove
// pictures in public/worksheet-figures/<worksheet id>/ and run \`npm run figures\`.
window.WORKSHEET_FIGURES = ${JSON.stringify(figures, null, 2)};
`;

fs.mkdirSync(root, { recursive: true });
const previous = fs.existsSync(output) ? fs.readFileSync(output, "utf8") : "";
if (previous !== content) fs.writeFileSync(output, content);

const count = Object.values(figures).reduce((sum, files) => sum + Object.keys(files).length, 0);
console.log(`Question pictures: ${count} in ${Object.keys(figures).length} worksheet folder(s)${previous === content ? " (unchanged)" : ""}.`);
for (const warning of warnings) console.warn(`  warning: ${warning}`);
